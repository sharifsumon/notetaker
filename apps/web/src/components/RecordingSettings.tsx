import { isValidTimeZone, type Me } from "@notetaker/shared";
import { useState } from "react";
import { browserTimeZone } from "../lib/format";
import { useUpdateSettings } from "../lib/queries";
import { errorText, Notice, useToast } from "./ui";

/** The recording notice shown before auto-recording or any registration (FR-03). */
export function RecordingNotice() {
  return (
    <div className="prose">
      <p>When you ask Notetaker to record a meeting:</p>
      <ul>
        <li>
          A bot named after you (for example “Asha’s Notetaker (recording)”) joins the call as a visible participant. It does
          not bypass lobbies, waiting rooms or host controls; the host may need to admit it.
        </li>
        <li>It records the meeting audio only, which is stored privately for your account.</li>
        <li>
          You are responsible for telling participants that the meeting is being recorded and for getting any consent required
          where they are. Some organizations do not allow recording bots.
        </li>
        <li>Only Google Meet and Microsoft Teams meetings are supported.</li>
        <li>Summaries and minutes are generated by AI and can contain mistakes. Review them before sharing.</li>
      </ul>
    </div>
  );
}

export function RecordingPreferences({ me, onDone, submitLabel = "Save preferences" }: { me: Me; onDone?: () => void; submitLabel?: string }) {
  const update = useUpdateSettings();
  const toast = useToast();
  const [ack, setAck] = useState(!!me.recordingNoticeAcknowledgedAt);
  const [auto, setAuto] = useState<"yes" | "no" | null>(me.autoRegister === null ? null : me.autoRegister ? "yes" : "no");
  const [tz, setTz] = useState(me.timezone === "UTC" && !me.recordingNoticeAcknowledgedAt ? browserTimeZone() : me.timezone);
  const zones = (Intl as unknown as { supportedValuesOf?: (k: string) => string[] }).supportedValuesOf?.("timeZone") ?? [tz];

  const submit = (e: React.FormEvent) => {
    e.preventDefault();
    update.mutate(
      {
        ...(ack && !me.recordingNoticeAcknowledgedAt ? { acknowledgeRecordingNotice: true as const } : {}),
        ...(auto ? { autoRegister: auto === "yes" } : {}),
        ...(isValidTimeZone(tz) ? { timezone: tz } : {}),
      },
      {
        onSuccess: () => {
          toast("Preferences saved");
          onDone?.();
        },
      },
    );
  };

  return (
    <form className="stack-lg" onSubmit={submit}>
      <fieldset className="stack">
        <legend className="visually-hidden">Recording notice</legend>
        <RecordingNotice />
        <label className="choice">
          <input type="checkbox" checked={ack} disabled={!!me.recordingNoticeAcknowledgedAt} onChange={(e) => setAck(e.target.checked)} required />
          <span>
            I understand how recording works and will inform participants.
            {me.recordingNoticeAcknowledgedAt && <small>Acknowledged on {new Date(me.recordingNoticeAcknowledgedAt).toLocaleDateString()}</small>}
          </span>
        </label>
      </fieldset>

      <fieldset className="stack">
        <legend>
          <h3>Which meetings should be recorded?</h3>
        </legend>
        <label className="choice">
          <input type="radio" name="auto" value="no" checked={auto === "no"} onChange={() => setAuto("no")} required />
          <span>
            Only meetings I choose
            <small>Synced meetings appear on your dashboard; select Record on the ones you want.</small>
          </span>
        </label>
        <label className="choice">
          <input type="radio" name="auto" value="yes" checked={auto === "yes"} onChange={() => setAuto("yes")} disabled={!ack} />
          <span>
            Every upcoming Meet and Teams meeting on my connected calendars
            <small>You can still cancel recording for any meeting before the bot joins.</small>
          </span>
        </label>
      </fieldset>

      <div className="field" style={{ maxWidth: "22rem" }}>
        <label htmlFor="tz">Time zone</label>
        <select id="tz" value={tz} onChange={(e) => setTz(e.target.value)}>
          {(zones.includes(tz) ? zones : [tz, ...zones]).map((z) => (
            <option key={z} value={z}>
              {z}
            </option>
          ))}
        </select>
        <span className="hint">Meeting times are shown in this time zone.</span>
      </div>

      {update.isError && <Notice tone="bad">{errorText(update.error)}</Notice>}
      <div>
        <button className="btn btn-primary" type="submit" disabled={update.isPending || !ack || !auto}>
          {submitLabel}
        </button>
      </div>
    </form>
  );
}
